#!/bin/bash
# =============================================================================
# Script:
# Obtain full taxonomic lineages for all TaxIDs associated with UniRef90
# DIAMOND hits using taxonkit, to enable family-level taxonomic attribution
# of metatranscriptomic read counts.
#
# Author (script):
# Henrique M. Dias
#
# Affiliation:
# South Dakota State University
#
# Date:
# 2026
#
# Description:
# Uses taxonkit to convert NCBI TaxIDs to full taxonomic lineages
# (kingdom → phylum → class → order → family → genus). Input is the
# unique set of TaxIDs from the UniRef90 hit mapping file generated by
# script 10_extract_uniref90_taxids.sh.
#
# Two taxonkit steps:
#   1. taxonkit lineage  : retrieves the full lineage string for each TaxID
#   2. taxonkit reformat : reformats into structured columns by rank
#
# Output columns:
#   TaxID | full_lineage | rank | kingdom | phylum | class | order | family | genus
#
# This file is joined downstream with uniref90_hits_taxid.tsv to map
# UniRef90_ID → TaxID → family, enabling per-sample read count aggregation
# at the family level for comparison with 16S/ITS amplicon data.
#
# Assumptions:
#   - Conda environment `metatx` contains taxonkit v0.20.0+
#   - NCBI taxonomy database (names.dmp, nodes.dmp) exists at TAXDUMP_DIR
#   - uniref90_hits_taxid.tsv exists (generated by script 10)
#
# Inputs:
#   TAXID_FILE  : UniRef90_ID → TaxID mapping (uniref90_hits_taxid.tsv)
#   TAXDUMP_DIR : NCBI taxonomy database directory (taxdump/)
#
# Outputs:
#   LINEAGE_FILE: TSV with TaxID and full lineage by rank (taxid_lineage.tsv)
#
# Usage:
#   sbatch 11_taxonkit_lineage.sh
#
# Notes:
#   - Only unique TaxIDs are processed (sort -u) for efficiency
#   - --fill-miss-rank fills missing ranks with placeholder names
#   - Runtime estimate: 5-15 min for ~500k unique TaxIDs
# =============================================================================
#SBATCH --job-name=taxonkit
#SBATCH --partition=compute
#SBATCH --cpus-per-task=8
#SBATCH --mem=16G
#SBATCH --time=2:00:00
#SBATCH --output=logs/taxonkit_%j.out
#SBATCH --error=logs/taxonkit_%j.err
#SBATCH --mail-type=END,FAIL
#SBATCH --mail-user=your.email@institution.edu

# ── Activate conda environment ────────────────────────────────────────────────
source ${HOME}/miniconda3/etc/profile.d/conda.sh
conda activate metatx

# ── Paths ─────────────────────────────────────────────────────────────────────
BASE_DIR=${PROJ}
TAXID_FILE=${BASE_DIR}/db/uniref90/uniref90_hits_taxid.tsv
TAXDUMP_DIR=${SCRATCH_DIR}/dbs/taxdump
LINEAGE_FILE=${BASE_DIR}/db/uniref90/taxid_lineage.tsv

echo "=========================================="
echo "Job ID   : $SLURM_JOB_ID"
echo "Started  : $(date)"
echo "=========================================="

# ── Get unique TaxIDs ─────────────────────────────────────────────────────────
echo "[$(date)] Extracting unique TaxIDs..."
N_TAXIDS=$(cut -f2 ${TAXID_FILE} | sort -u | wc -l)
echo "  Unique TaxIDs: ${N_TAXIDS}"

# ── Run taxonkit lineage + reformat ──────────────────────────────────────────
echo "[$(date)] Running taxonkit lineage and reformat..."

cut -f2 ${TAXID_FILE} | \
    sort -u | \
    taxonkit lineage \
        --data-dir ${TAXDUMP_DIR} \
        --show-rank \
        --threads ${SLURM_CPUS_PER_TASK} | \
    taxonkit reformat \
        --data-dir ${TAXDUMP_DIR} \
        --format "{k}\t{p}\t{c}\t{o}\t{f}\t{g}" \
        --fill-miss-rank \
        --threads ${SLURM_CPUS_PER_TASK} \
    > ${LINEAGE_FILE}

echo "[$(date)] Done: $(wc -l < ${LINEAGE_FILE}) TaxIDs annotated"
echo "Output: ${LINEAGE_FILE}"
echo "Preview:"
head -3 ${LINEAGE_FILE}

echo "=========================================="
echo "Finished: $(date)"
echo "=========================================="
